#!/usr/bin/env node
// Comment threads with 3 to 6 levels of replies on every post, shot and pose. Seeded and idempotent:
// generated replies (ids `tx…`, and deepen-data's `g_tc_…`) are rebuilt on every run; hand-written comments are kept
// (anything deeper than 6 levels is folded up to level 6). Run last: node scripts/threads.mjs
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const DATA = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'data');
const read = (f) => JSON.parse(readFileSync(join(DATA, f), 'utf8'));
const hash = (s) => [...s].reduce((h, c) => (Math.imul(h, 31) + c.charCodeAt(0)) >>> 0, 7) || 1;
const rngOf = (seed) => { let x = (hash(String(seed)) % 2147483646) + 1; return () => ((x = (x * 16807) % 2147483647) - 1) / 2147483646; };
const int = (r, lo, hi) => lo + Math.floor(r() * (hi - lo + 1)); const pick = (r, a) => a[Math.floor(r() * a.length)];

const core = read('core.json'), agents = read('agents.json'), feed = read('feed.json'), threads = read('threads.json');
const people = [...core.users.map((u) => u.id), ...agents.agents.map((a) => a.id)];
const MIN = 3, MAX = 6;

// What people say at each level: an opinion, a question about it, an answer, a follow-up, a joke, a sign-off.
const LEVEL = [
  ['This is the one I keep rewatching.', 'The shoulders do all the work here.', 'Need this in the Rare edition.', 'The colour on this is unreal.', 'Who did the fitting?', 'Saving this for Saturday.', 'Front row was worth it for this alone.', 'The hem is perfect on the avatar too.'],
  ['Is the avatar version out yet?', 'Which pool is it in?', 'Does it come in the darker shade?', 'Did you swap for it or buy it outright?', 'What size are you wearing?', 'Is it a pack or a solo look?'],
  ['Out Friday, the pool page has the timer.', 'Solo look, but there is a pack with the gloves.', 'Swapped my old tote, the pool paid the difference.', 'Darker shade drops next week, same pool.', 'True to size, the agent checked the fit.', 'Bought it outright before the price moved.'],
  ['Wait, the pool pays the difference? Since when?', 'How much did the price move after?', 'Was the swap under your withdraw limit?', 'Did the agent pick the shade or did you?', 'Which agent, the house concierge?'],
  ['Up to the weekly limit, after that it is straight barter.', 'About four percent in an hour, then it came back.', 'Well under, I only swap small pieces.', 'The concierge picked it, I just said evening.', 'Same one, ask about the gloves.'],
  ['Good to know, thank you.', 'Doing exactly this tonight.', 'See you at the show then.', 'This thread is more useful than the docs.', 'Noted, swapping on Friday.', 'Ha, the gloves got me too.'],
];

const ids = new Set();
const posts = [...feed.shots.map((s) => s.id), ...agents.posts.map((p) => p.id)];
// Generated by deepen-data (g_tc_) or by this script (tx): rebuilt here. Hand-written ones are kept.
const kept = threads.comments.filter((c) => !/^(tx|g_tc_)/.test(c.id));
// Fold anything deeper than MAX up to MAX (re-parent onto the ancestor at MAX-1).
const byId = new Map(kept.map((c) => [c.id, c]));
for (const c of kept) {
  if (c.depth <= MAX) continue;
  let p = byId.get(c.parentId); while (p && p.depth > MAX - 1) p = byId.get(p.parentId);
  if (p) { c.parentId = p.id; c.depth = p.depth + 1; }
}
const targets = new Set([...posts, ...kept.map((c) => c.targetId)]);
const out = [...kept]; kept.forEach((c) => ids.add(c.id));
let added = 0; let seq = 0; const nextId = () => 'tx' + (seq++).toString(36);
for (const target of targets) {
  const r = rngOf('tx:' + target);
  const mine = out.filter((c) => c.targetId === target);
  const want = int(r, MIN, MAX); // the deepest reply level this thread reaches
  let roots = mine.filter((c) => c.depth === 0);
  // Every post gets 2 to 4 top-level comments.
  for (let k = roots.length; k < int(r, 2, 3); k++) {
    const c = { id: nextId(), targetId: target, parentId: null, depth: 0, authorId: pick(r, people), text: pick(r, LEVEL[0]), likes: int(r, 5, 900), at: int(r, 1, 23) + 'h' };
    out.push(c); mine.push(c); added++;
  }
  roots = mine.filter((c) => c.depth === 0);
  // The first root grows a chain down to `want` levels; every level may branch once more.
  const grow = (parent, depth, limit, tag) => {
    if (depth > limit) return;
    const branches = depth === 1 ? int(r, 1, 2) : r() < 0.15 ? 2 : 1;
    for (let b = 0; b < branches; b++) {
      const id = nextId();
      const c = { id, targetId: target, parentId: parent.id, depth, authorId: pick(r, people), text: pick(r, LEVEL[Math.min(depth, LEVEL.length - 1)]), likes: int(r, 0, 300 >> depth), at: int(r, 1, 23) + 'h' };
      out.push(c); added++;
      grow(c, depth + 1, b === 0 ? limit : Math.min(limit, depth + int(r, 0, 1)), tag);
    }
  };
  roots.forEach((root, k) => {
    const deepest = Math.max(0, ...mine.filter((c) => c.parentId === root.id || c.id === root.id).map((c) => c.depth));
    if (deepest >= (k === 0 ? want : 1)) return;
    grow(root, 1, k === 0 ? want : int(r, 1, 2), String.fromCharCode(97 + k));
  });
}
threads.comments = out;
threads.maxDepth = MAX;
threads.note = 'Mock threads for in-house assessment. Fictional people only. Every thread reaches 3 to 6 levels of replies.';
writeFileSync(join(DATA, 'threads.json'), JSON.stringify(threads));
// Shards: the app loads only the shard a post's thread lives in (src/lib/lazy.ts: useThreadFor), ~1/16 of the file.
export const SHARDS = 16; const shardOf = (id) => [...id].reduce((h, c) => (Math.imul(h, 31) + c.charCodeAt(0)) >>> 0, 7) % SHARDS;
mkdirSync(join(DATA, 'threads'), { recursive: true });
const shards = Array.from({ length: SHARDS }, () => []); out.forEach((c) => shards[shardOf(c.targetId)].push(c));
shards.forEach((list, i) => writeFileSync(join(DATA, 'threads', String(i).padStart(2, '0') + '.json'), JSON.stringify({ comments: list })));
// Comment counts per post, loaded up front (threads.json itself loads lazily when a post opens).
const counts = {}; out.forEach((c) => (counts[c.targetId] = (counts[c.targetId] ?? 0) + 1));
writeFileSync(join(DATA, 'threadCounts.json'), JSON.stringify(counts));
const depth = new Map(); out.forEach((c) => depth.set(c.targetId, Math.max(depth.get(c.targetId) ?? 0, c.depth)));
const dist = {}; depth.forEach((d) => (dist[d] = (dist[d] ?? 0) + 1));
console.log(`threads: ${out.length} comments on ${depth.size} targets (+${added}) · deepest reply level per thread:`, dist);
