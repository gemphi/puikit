#!/usr/bin/env node
// Build every app in this repo for one-origin production hosting and collect the dists under dist-all/.
//   node build-all.mjs            build all apps that have source here
//   node build-all.mjs phisum …   build only the named apps
// Each app is built with base=/<key>/, VITE_PHI_API=/api (data from Phiora on the same origin) and
// VITE_PHI_APPS_BASE=/ (cross-app links resolve to /<key>/). Then nginx.conf is written to serve them.
import { execFileSync } from 'node:child_process';
import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const registry = JSON.parse(readFileSync(join(here, 'phi-kit', 'src', 'registry.json'), 'utf8'));
const DIST = join(here, 'dist-all');

// The apps we can build from source here: a registry key with its own package.json + vite build.
const buildable = registry
  .map((a) => a.key)
  .filter((k) => existsSync(join(here, k, 'package.json')) && existsSync(join(here, k, 'vite.config.ts')));
// --backend python routes nginx /api/ to the phiadk container (Phiora FastAPI, :4400); default is the Node one.
const backendIx = process.argv.indexOf('--backend');
const backend = backendIx > -1 ? process.argv[backendIx + 1] : 'node';
const apiUpstream = backend === 'python' ? 'http://phiadk:4400/' : 'http://phiora:4300/';
const want = process.argv.slice(2).filter((a, i) => a !== '--backend' && (backendIx === -1 || i !== backendIx - 1));
const keys = want.length ? buildable.filter((k) => want.includes(k)) : buildable;
if (!keys.length) { console.error('Nothing to build. Known:', buildable.join(', ')); process.exit(1); }

mkdirSync(DIST, { recursive: true });
for (const key of keys) {
  process.stdout.write(`\nbuilding ${key} … `);
  execFileSync('npm', ['run', 'build'], {
    cwd: join(here, key),
    stdio: ['ignore', 'ignore', 'inherit'],
    env: { ...process.env, PHI_BASE: `/${key}/`, VITE_PHI_API: '/api', VITE_PHI_APPS_BASE: '/' },
  });
  const out = join(DIST, key);
  rmSync(out, { recursive: true, force: true });
  cpSync(join(here, key, 'dist'), out, { recursive: true });
  console.log('ok');
}

// The apps served: everything now present under dist-all (built this run or kept from a prior build, e.g. phipad).
const served = registry.map((a) => a.key).filter((k) => existsSync(join(DIST, k, 'index.html')));
const first = served.includes('phiegg') ? 'phiegg' : served[0];
const conf = `# Generated by build-all.mjs — one origin for every Phiace app, with /api proxied to Phiora.
server {
  listen 80;
  root /usr/share/nginx/html;
  gzip on; gzip_types text/css application/javascript application/json image/svg+xml font/woff2;
  location = / { return 302 /${first}/; }
  location /api/ { proxy_pass ${apiUpstream}; proxy_set_header Host $host; proxy_set_header X-Forwarded-Proto $scheme; proxy_read_timeout 60s; }
${served.map((k) => `  location /${k}/ { try_files $uri $uri/ /${k}/index.html; }`).join('\n')}
}
`;
writeFileSync(join(DIST, 'nginx.conf'), conf);
console.log(`\nwrote dist-all/nginx.conf — serving: ${served.join(', ')} (/ → /${first}/)`);
